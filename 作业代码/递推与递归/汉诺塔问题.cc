// ## 五、 汉诺塔的惊人复杂度：$O(2^n)$

// 汉诺塔问题有一个非常著名的传说：印度的僧侣在日夜不停地移动 64 个黄金圆盘，当 64 个圆盘全部移完之日，就是世界毁灭之时。这其实是一个数学玩笑。

// 我们来看看移动 $n$ 个圆盘需要多少步（记为 $f(n)$）：

// * $f(1) = 1$
// * $f(2) = 2 \times 1 + 1 = 3$
// * $f(3) = 2 \times 3 + 1 = 7$
// * 数学规律：**$f(n) = 2^n - 1$**

// 汉诺塔的时间复杂度是恐怖的 **$O(2^n)$ 指数级**。
// 如果圆盘数量 $n = 64$，总共需要移动 $2^{64} - 1 = 18,446,744,073,709,551,615$ 步。即使僧侣一秒钟挪动一下，也需要大约 **5845 亿年** 才能挪完（而宇宙至今的年龄才 138 亿年）。

// 在算法竞赛中，如果看到汉诺塔变型题，一定要极度警惕 $n$ 的大小，超过 30 基本上就无法通过普通的递归穷举输出了。
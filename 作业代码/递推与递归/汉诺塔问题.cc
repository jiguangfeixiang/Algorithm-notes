// ## 四、 运行样例追踪（当 $n = 3$ 时）

// 如果你输入 `3`，程序会打印出如下步骤：

// 1. 盘子 1: 从 A 移动到 C
// 2. 盘子 2: 从 A 移动到 B
// 3. 盘子 1: 从 C 移动到 B  *(此时前2个盘子都成功挪到了B)*
// 4. 盘子 3: 从 A 移动到 C  *(最大盘成功就位C)*
// 5. 盘子 1: 从 B 移动到 A
// 6. 盘子 2: 从 B 移动到 C
// 7. 盘子 1: 从 A 移动到 C  *(全部在C搞定)*


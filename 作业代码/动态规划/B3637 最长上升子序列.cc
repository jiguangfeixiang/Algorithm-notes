#include <iostream>
#include <vector>
#include <algorithm>

using namespace std;

int main() {

    int n;
    if (!(cin >> n)) return 0;

    vector<int> nums(n);
    for (int i = 0; i < n; ++i) {
        cin >> nums[i];
    }

    // dp[i] 表示以 nums[i] 结尾的最长上升子序列长度，初始全为 1
    vector<int> dp(n+1, 1);
    int ans = 1; // 记录全局最大长度

    for (int i = 1; i <= n; ++i) {
        for (int j = 1; j < i; ++j) {
            // 只有当当前数大于前面的数时，才能接上去
            if (nums[i-1] > nums[j-1]) {
                dp[i] = max(dp[i], dp[j] + 1);
            }
        }
        ans = max(ans, dp[i]); // 更新全局最大值
    }

    cout << ans << "\n";

    return 0;
}   

// 最长上升子序列（Longest Increasing Subsequence，简称 **LIS**）是算法竞赛里最经典的动态规划模型之一。

// 想出状态转移方程的关键，在于**搞清楚“每个状态代表什么”**以及**“它是怎么从前面的状态推导出来的”**。

// ---

// ### 第一步：如何定义状态 $dp[i]$？

// 在序列问题中，一个极度常用且核心的套路是：**定义 $dp[i]$ 为以第 $i$ 个数结尾的最长上升子序列的长度。**

// * **为什么必须强调“以第 $i$ 个数结尾”？**
// 因为只有知道了子序列的**最后一个数**是谁，我们在往后接新数字的时候，才能判断这个新数字是不是比前一个数大（是否满足“严格递增”）。

// ---

// ### 第二步：如何寻找状态转移方程？

// 假设我们现在要求 $dp[i]$（即以第 $i$ 个数字 $a[i]$ 结尾的最长上升子序列）：

// 1. **基本底线**：$a[i]$ 自己一个人单独组成一个长度为 1 的子序列，所以初始时 $dp[i] = 1$。
// 2. **寻找接应者**：我们在 $i$ 之前找一个位置 $j$（即 $1 \le j < i$）。
// * 如果满足 $a[j] < a[i]$，说明 $a[i]$ 可以**接在**以 $a[j]$ 结尾的那个上升子序列的后面！
// * 一旦接上去，新序列的长度就会变成 $dp[j] + 1$。


// 3. **取最大值**：因为前面可能有多个满足条件的 $j$，我们要选能凑出最长序列的那一个：

// $$dp[i] = \max_{1 \le j < i, \, a[j] < a[i]} (dp[j] + 1)$$



// ---

// ### 举个例子：以样例 `1 2 4 1 3 4` 为例

// 设序列为 $a = [1, 2, 4, 1, 3, 4]$：

// * $a[1] = 1$: 没有前面的数， $dp[1] = 1$。
// * $a[2] = 2$: 前面 $a[1]=1 < 2$，可以接在它后面， $dp[2] = dp[1] + 1 = 2$。
// * $a[3] = 4$: 前面 $a[1], a[2]$ 都比 $4$ 小，接在 $a[2]$ 后面最长， $dp[3] = dp[2] + 1 = 3$ （序列：`1 2 4`）。
// * $a[4] = 1$: 前面没有比 $1$ 小的数，只能自己成立， $dp[4] = 1$。
// * $a[5] = 3$: 前面比 $3$ 小的有 $a[1]=1, a[2]=2, a[4]=1$。选接在 $a[2]$ 后面最长， $dp[5] = dp[2] + 1 = 3$ （序列：`1 2 3`）。
// * $a[6] = 4$: 前面比 $4$ 小的有 $a[1], a[2], a[3]=4(\text{不行}), a[4], a[5]=3$。接在 $a[5]$ 或 $a[3]$ 后面都可以达到最长， $dp[6] = dp[5] + 1 = 4$ （序列：`1 2 3 4`）。

// 最后，**答案不是 $dp[n]$**，而是整个 $dp$ 数组里的**最大值** $\max(dp[1 \dots n])$（因为最长子序列不一定是以最后一个数结尾）。

